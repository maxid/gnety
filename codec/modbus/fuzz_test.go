package modbus

import "testing"

// FuzzDecodePDU checks that no PDU byte sequence, however malformed, makes the
// decoder panic.
//
// The seed corpus covers every modeled function code, the exception form and a
// few truncated shapes. A rejected PDU is as interesting as an accepted one, so
// the target only requires that DecodePDU returns.
func FuzzDecodePDU(f *testing.F) {
	f.Add([]byte{})
	f.Add([]byte{0x01, 0x00, 0x13, 0x00, 0x25})
	f.Add([]byte{0x02, 0x00, 0xc4, 0x00, 0x16})
	f.Add([]byte{0x03, 0x00, 0x6b, 0x00, 0x03})
	f.Add([]byte{0x04, 0x00, 0x08, 0x00, 0x01})
	f.Add([]byte{0x05, 0x00, 0xac, 0xff, 0x00})
	f.Add([]byte{0x05, 0x00, 0xac, 0x00, 0x00})
	f.Add([]byte{0x06, 0x00, 0x01, 0x00, 0x03})
	f.Add([]byte{0x0f, 0x00, 0x13, 0x00, 0x0a, 0x02, 0xcd, 0x01})
	f.Add([]byte{0x10, 0x00, 0x01, 0x00, 0x02, 0x04, 0x00, 0x0a, 0x01, 0x02})
	f.Add([]byte{0x83, 0x02})
	f.Add([]byte{0x83})
	f.Add([]byte{0x0f, 0x00, 0x13, 0x00, 0x0a, 0x02, 0xcd})
	f.Add([]byte{0x03, 0x00, 0x00, 0x07, 0xd1})
	f.Add([]byte{0x00})
	f.Add([]byte{0x07, 0x00, 0x00})
	f.Fuzz(func(t *testing.T, pdu []byte) {
		_, _ = DecodePDU(pdu)
	})
}
